-- READ-ONLY query examples assuming SALES_PORTFOLIO_TEST.PUBLIC.RAW_SALES is loaded.
-- Not independently run against the packaged data (source CSV is not included).
SELECT COUNT(*) AS ROW_COUNT,
       COUNT(DISTINCT ORDERNUMBER) AS DISTINCT_ORDER_NUMBERS
FROM SALES_PORTFOLIO_TEST.PUBLIC.RAW_SALES;

SELECT COUNTRY,
       COUNT(*) AS LINE_ITEMS,
       SUM(COALESCE(SALES,0)) AS TOTAL_SALES
FROM SALES_PORTFOLIO_TEST.PUBLIC.RAW_SALES
GROUP BY COUNTRY
ORDER BY TOTAL_SALES DESC;

SELECT ORDERNUMBER, COUNTRY, SALES,
       ROW_NUMBER() OVER (
           PARTITION BY COUNTRY ORDER BY SALES DESC, ORDERNUMBER
       ) AS COUNTRY_SALES_RANK
FROM SALES_PORTFOLIO_TEST.PUBLIC.RAW_SALES;

-- Read-only RAW -> CLEAN example adapted from the historical project worksheet.
-- This SELECT does not create or update tables.
-- Keep one row per original sales line: ORDERNUMBER can repeat across line items.
-- Example only; not rerun against the missing source dataset.
WITH cleaned_sales AS (
    SELECT
        ORDERNUMBER,
        ORDERLINENUMBER,
        UPPER(TRIM(CUSTOMERNAME)) AS CLEAN_CUSTOMER_NAME,
        UPPER(TRIM(COUNTRY)) AS CLEAN_COUNTRY,
        UPPER(TRIM(STATUS)) AS CLEAN_STATUS,
        UPPER(TRIM(PRODUCTLINE)) AS CLEAN_PRODUCTLINE,
        COALESCE(SALES, 0) AS CLEAN_SALES,
        COALESCE(QUANTITYORDERED, 0) AS CLEAN_QUANTITYORDERED,
        COALESCE(PRICEEACH, 0) AS CLEAN_PRICEEACH,
        TRY_TO_DATE(ORDERDATE, 'MM/DD/YYYY HH24:MI') AS CLEAN_ORDER_DATE,
        CASE
            WHEN COALESCE(SALES, 0) > 5000 THEN 'HIGH'
            WHEN COALESCE(SALES, 0) > 1000 THEN 'MEDIUM'
            ELSE 'LOW'
        END AS SALES_CATEGORY
    FROM SALES_PORTFOLIO_TEST.PUBLIC.RAW_SALES
)
SELECT
    CLEAN_COUNTRY,
    SALES_CATEGORY,
    COUNT(*) AS LINE_ITEMS,
    SUM(CLEAN_SALES) AS TOTAL_SALES
FROM cleaned_sales
GROUP BY CLEAN_COUNTRY, SALES_CATEGORY
ORDER BY TOTAL_SALES DESC;

-- Country-level average compared with each sales line.
WITH cleaned_sales AS (
    SELECT
        ORDERNUMBER,
        ORDERLINENUMBER,
        UPPER(TRIM(COUNTRY)) AS CLEAN_COUNTRY,
        COALESCE(SALES, 0) AS CLEAN_SALES
    FROM SALES_PORTFOLIO_TEST.PUBLIC.RAW_SALES
)
SELECT
    ORDERNUMBER,
    ORDERLINENUMBER,
    CLEAN_COUNTRY,
    CLEAN_SALES,
    AVG(CLEAN_SALES) OVER (
        PARTITION BY CLEAN_COUNTRY
    ) AS COUNTRY_AVG_LINE_SALES
FROM cleaned_sales
ORDER BY CLEAN_COUNTRY, ORDERNUMBER, ORDERLINENUMBER;
